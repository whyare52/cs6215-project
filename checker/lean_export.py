"""Export a spec to a Lean module that certifies its safe agents with `Ir.closed_sound`.

By default the theorems cover the agents Python finds unreachable. `--claim-principal P`
instead claims every agent `node@P` safe, so Lean, not Python, decides the claim, and the module
fails to check when some agent of `P` is reachable. It then also states the claim as one theorem,
`principal_safe`.

`--ordered` takes the output of `lgtrace.ordered_dict` instead of a spec and writes a module for
the ordered analysis (`to_lean_ordered`). It keeps the `Closed` certificate and adds the flow
summary, the closed taint state that bounds every schedule, and each traced schedule with its
kills, each checked by `decide`.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import ordered
from irspec import Spec, from_dict, holders, load, reach


def _ident(name: str) -> str:
  cleaned = re.sub(r"\W", "_", name)
  return cleaned if cleaned[:1].isalpha() else f"x_{cleaned}"


def _pairs(pairs: list[tuple[int, int]]) -> str:
  return "[" + ", ".join(f"({i}, {j})" for i, j in pairs) + "]"


def _nats(xs: list[int]) -> str:
  return "[" + ", ".join(map(str, xs)) + "]"


def principal_agents(spec: Spec, principal: str) -> list[str]:
  return [a for a in spec.agents if a.rpartition("@")[2] == principal]


def to_lean(spec: Spec, namespace: str, tactic: str = "decide",
            claim: list[str] | None = None) -> str:
  ag = {a: i for i, a in enumerate(spec.agents)}
  bd = {b: i for i, b in enumerate(spec.boards)}
  vr = {v: i for i, v in enumerate(spec.vars)}
  n_a, n_b, n_v = len(ag), max(len(bd), 1), max(len(vr), 1)
  reader = sorted((bd[b], ag[a]) for b in spec.boards for a in spec.readers_of(b))
  writer = sorted((bd[b], ag[a]) for b in spec.boards for a in spec.writers_of(b))
  sees = sorted((ag[a], vr[v]) for a, vs in spec.sees.items() for v in vs)
  owners = [ag[spec.owner[v]] for v in spec.vars] or [0]
  safe = claim if claim is not None else [a for a in spec.agents if a not in reach(spec)]
  legend = "\n".join(
    [*(f"- agent {i} is {a}" for a, i in ag.items()),
     *(f"- board {i} is {b}" for b, i in bd.items()),
     *(f"- variable {i} is {v}" for v, i in vr.items())]
  )
  theorems = "\n\n".join(
    f"theorem safe_{_ident(a)} : ¬ Reach cfg adv ({ag[a]} : Fin {n_a}) := fun hr => by\n"
    f"  have := closed_sound world closed hr\n"
    f"  revert this; decide"
    for a in safe
  )
  if claim is not None:
    theorems += (
      f"\n\ntheorem principal_safe : ∀ a : Fin {n_a}, a.val ∈ {_nats([ag[a] for a in safe])}"
      f" → ¬ Reach cfg adv a := by\n"
      f"  have h : ∀ a : Fin {n_a}, a.val ∈ {_nats([ag[a] for a in safe])} →"
      f" safeOf cfg adv world a = true := by decide\n"
      f"  intro a ha hr\n"
      f"  have := closed_sound world closed hr\n"
      f"  rw [h a ha] at this; exact Bool.noConfusion this")
  return f"""import Ir.Check

/-!
Generated by `checker/lean_export.py`. Do not edit.

{legend}
-/

namespace {namespace}

open Ir

def cfg : Config (Fin {n_a}) (Fin {n_b}) (Fin {n_v}) Nat String where
  reader b a := decide ((b.val, a.val) ∈ ({_pairs(reader)} : List (Nat × Nat)))
  writer b a := decide ((b.val, a.val) ∈ ({_pairs(writer)} : List (Nat × Nat)))
  owner v := ({_nats(owners)} : List (Fin {n_a})).getD v.val 0
  sees a v := decide ((a.val, v.val) ∈ ({_pairs(sees)} : List (Nat × Nat)))
  echoSees v := decide (v.val ∈ ({_nats(sorted(vr[v] for v in spec.echo_sees))} : List Nat))
  echo _ := "action_executed"

def adv : Adversary (Fin {n_a}) (Fin {n_b}) where
  controls a := decide (a.val ∈ ({_nats(sorted(ag[a] for a in spec.controls))} : List Nat))
  injects b := decide (b.val ∈ ({_nats(sorted(bd[b] for b in spec.injects))} : List Nat))

def world : Universe (Fin {n_a}) (Fin {n_b}) (Fin {n_v}) where
  agents := List.finRange {n_a}
  boards := List.finRange {n_b}
  vars := List.finRange {n_v}
  hA := by decide
  hB := by decide
  hV := by decide

theorem closed : Closed cfg adv world (safeOf cfg adv world) := by
  {tactic}

{theorems}

end {namespace}
"""


def _list(xs: list[str], ty: str) -> str:
  return f"([{', '.join(xs)}] : List {ty})"


def _wrap(items: list[str], indent: str = "    ", width: int = 96) -> str:
  """Items joined by commas, broken into lines under `width`."""
  lines, line = [], ""
  for item in items:
    piece = (", " if line else "") + item
    if len(indent) + len(line) + len(piece) > width and line:
      lines.append(line + ",")
      line = item
    else:
      line += piece
  lines.append(line)
  return ("\n" + indent).join(lines)


def _nat_list(xs: list[int], ty: str = "Nat") -> str:
  return f"([{_wrap([str(x) for x in xs])}] : List {ty})"


def _tuple_list(xs: list[tuple[int, ...]], ty: str) -> str:
  return f"([{_wrap(['(' + ', '.join(map(str, x)) + ')' for x in xs])}] : List ({ty}))"


def to_lean_ordered(data: dict, namespace: str, tactic: str = "decide") -> str:
  """A module certifying the ordered analysis of `data`, an `lgtrace.ordered_dict` export.

  - `closed`, the `Closed` certificate of `Reach`, as `to_lean` writes it.
  - `summary`, the uniform flow summary. `tAll_closed` checks `closedB` for the closed taint
    state `tAll`, so `every_schedule` and `every_schedule_board` give noninterference of each
    agent and board it leaves untainted on every schedule.
  - Per traced script `k`, the expanded schedule `sched_k` and `summary_k`, the summary with
    that schedule's kills. `safe_k_ok` and `tainted_k_ok` decide which agents end tainted, and
    `ni_k` gives noninterference of each untainted agent on that schedule. `respects_k` shows that a
    policy respecting `summary_k` respects `summary`.
  """
  spec = from_dict(data["spec"])
  if spec.vars:
    raise ValueError("the ordered export takes specs without variables")
  ag = {a: i for i, a in enumerate(spec.agents)}
  bd = {b: i for i, b in enumerate(spec.boards)}
  n_a, n_b = len(ag), len(bd)
  fa, fb = f"Fin {n_a}", f"Fin {n_b}"
  m = ordered.model(data)
  reader = sorted((bd[b], ag[a]) for b in spec.boards for a in spec.readers_of(b))
  writer = sorted((bd[b], ag[a]) for b in spec.boards for a in spec.writers_of(b))
  refined = sorted((ag[x], bd[o]) for (x, o) in m.dep)
  deps = sorted((ag[x], bd[o], bd[i]) for (x, o), ins in m.dep.items() for i in ins)
  legend = "\n".join([*(f"- agent {i} is {a}" for a, i in ag.items()),
                      *(f"- board {i} is {b}" for b, i in bd.items())])
  every = ordered.closure(data)
  safe_all = [ag[a] for a in spec.agents if a not in every.agents]
  clean_all = [bd[b] for b in spec.boards if b not in every.boards]
  blocks = []
  for k, w in enumerate(ordered.traced(data)):
    sched = [f".agent {ag[t.agent]}" for t in w.turns]
    kills = sorted((n, ag[t.agent], bd[b]) for n, t in enumerate(w.turns) for b in t.kills)
    safe = [ag[a] for a in spec.agents if a not in w.taint.agents]
    tainted = [ag[a] for a in spec.agents if a in w.taint.agents]
    blocks.append(f"""/-! ### Script {w.script}, {len(w.turns)} turns -/

def sched_{k} : List (Turn ({fa})) :=
  [{_wrap(sched, "   ")}]

/-- Kills of this schedule, as (turn index, agent, board). -/
def kills_{k} : List (Nat × Nat × Nat) :=
  {_tuple_list(kills, "Nat × Nat × Nat")}

def summary_{k} : Summary ({fa}) ({fb}) Empty where
  dep x _ := dep x
  kills x n b := decide ((n, x.val, b.val) ∈ kills_{k})

theorem respects_{k} {{honest : Behaviour ({fa}) ({fb}) Empty Nat String}}
    (hR : Respects summary_{k} honest) : Respects summary honest :=
  hR.of_kills rfl fun _ _ _ h => by simp [summary, Summary.uniform] at h

def safe_{k} : List ({fa}) := {_nat_list(safe, f"({fa})")}

def tainted_{k} : List ({fa}) := {_nat_list(tainted, f"({fa})")}

theorem safe_{k}_ok :
    (safe_{k}.all fun a => !reachSum cfg adv world summary_{k} sched_{k} a) = true := by
  {tactic}

theorem tainted_{k}_ok :
    (tainted_{k}.all fun a => reachSum cfg adv world summary_{k} sched_{k} a) = true := by
  {tactic}

theorem ni_{k} {{honest : Behaviour ({fa}) ({fb}) Empty Nat String}}
    (hR : Respects summary_{k} honest) (adv₁ adv₂ : Attack ({fa}) ({fb}) Empty Nat String)
    (s₀ : State ({fa}) ({fb}) Empty Nat String) {{a : {fa}}} (ha : a ∈ safe_{k})
    (o : Loc ({fb}) Empty) :
    (actionsOf cfg adv honest adv₁ a sched_{k} s₀).map (List.filter (Action.touches o)) =
      (actionsOf cfg adv honest adv₂ a sched_{k} s₀).map (List.filter (Action.touches o)) := by
  exact reachSum_sound hR adv₁ adv₂ s₀ sched_{k} a
    (by simpa using List.all_eq_true.1 safe_{k}_ok a ha) o""")
  scripts = "\n\n".join(blocks)
  return f"""import Ir.Check
import Ir.OrderedClosed

/-!
Generated by `checker/lean_export.py --ordered`. Do not edit.

{legend}
-/

namespace {namespace}

open Ir

set_option maxRecDepth 100000

/-- (board, agent) pairs. -/
def readers : List (Nat × Nat) :=
  {_tuple_list(reader, "Nat × Nat")}

/-- (board, agent) pairs. -/
def writers : List (Nat × Nat) :=
  {_tuple_list(writer, "Nat × Nat")}

def cfg : Config ({fa}) ({fb}) Empty Nat String where
  reader b a := decide ((b.val, a.val) ∈ readers)
  writer b a := decide ((b.val, a.val) ∈ writers)
  owner v := nomatch v
  sees _ v := nomatch v
  echoSees v := nomatch v
  echo _ := "action_executed"

def adv : Adversary ({fa}) ({fb}) where
  controls a := decide (a.val ∈ {_nat_list(sorted(ag[a] for a in spec.controls))})
  injects b := decide (b.val ∈ {_nat_list(sorted(bd[b] for b in spec.injects))})

def world : Universe ({fa}) ({fb}) Empty where
  agents := List.finRange {n_a}
  boards := List.finRange {n_b}
  vars := []
  hA := by decide
  hB := by decide
  hV v := nomatch v

theorem closed : Closed cfg adv world (safeOf cfg adv world) := by
  {tactic}

/-! ## The flow summary

Outputs of code agents that only copy a key's old value depend on the boards of that key the
agent reads, listed as (agent, output, input). Every other output depends on every input. -/

def refined : List (Nat × Nat) :=
  {_tuple_list(refined, "Nat × Nat")}

def deps : List (Nat × Nat × Nat) :=
  {_tuple_list(deps, "Nat × Nat × Nat")}

def dep (x : {fa}) : Loc ({fb}) Empty → Loc ({fb}) Empty → Bool
  | .board o, .board i =>
    !decide ((x.val, o.val) ∈ refined) || decide ((x.val, o.val, i.val) ∈ deps)
  | _, _ => true

def summary : Summary ({fa}) ({fb}) Empty := Summary.uniform dep fun _ _ => false

/-! ## Every schedule -/

def tAll : Taint ({fa}) ({fb}) Empty where
  board b := decide (b.val ∈ {_nat_list(sorted(bd[b] for b in every.boards))})
  var v := nomatch v
  agent a := decide (a.val ∈ {_nat_list(sorted(ag[a] for a in every.agents))})

theorem tAll_closed : closedB cfg adv world dep (fun _ _ => false) tAll = true := by
  {tactic}

def safeAll : List ({fa}) := {_nat_list(safe_all, f"({fa})")}

def cleanAll : List ({fb}) := {_nat_list(clean_all, f"({fb})")}

theorem safeAll_ok : (safeAll.all fun a => !tAll.agent a) = true := by
  {tactic}

theorem cleanAll_ok : (cleanAll.all fun b => !tAll.board b) = true := by
  {tactic}

theorem every_schedule {{honest : Behaviour ({fa}) ({fb}) Empty Nat String}}
    (hR : Respects summary honest) (adv₁ adv₂ : Attack ({fa}) ({fb}) Empty Nat String)
    (s₀ : State ({fa}) ({fb}) Empty Nat String) (sched : List (Turn ({fa})))
    {{a : {fa}}} (ha : a ∈ safeAll) (o : Loc ({fb}) Empty) :
    (actionsOf cfg adv honest adv₁ a sched s₀).map (List.filter (Action.touches o)) =
      (actionsOf cfg adv honest adv₂ a sched s₀).map (List.filter (Action.touches o)) := by
  exact every_schedule_sound tAll_closed hR adv₁ adv₂ s₀ sched
    (by simpa using List.all_eq_true.1 safeAll_ok a ha) o

theorem every_schedule_board {{honest : Behaviour ({fa}) ({fb}) Empty Nat String}}
    (hR : Respects summary honest) (adv₁ adv₂ : Attack ({fa}) ({fb}) Empty Nat String)
    (s₀ : State ({fa}) ({fb}) Empty Nat String) (sched : List (Turn ({fa})))
    {{b : {fb}}} (hb : b ∈ cleanAll) :
    (run cfg adv honest adv₁ sched s₀).logs b = (run cfg adv honest adv₂ sched s₀).logs b := by
  exact every_schedule_board_sound tAll_closed hR adv₁ adv₂ s₀ sched
    (by simpa using List.all_eq_true.1 cleanAll_ok b hb)

/-! ## Traced schedules -/

{scripts}

end {namespace}
"""


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("spec", type=Path)
  parser.add_argument("out", type=Path)
  parser.add_argument("--namespace", default="Generated")
  parser.add_argument("--holders", nargs="*", help="certify confidentiality for these holders")
  parser.add_argument("--tactic", default="decide")
  parser.add_argument("--claim-principal", metavar="P",
                      help="claim every agent node@P safe, whatever Python finds")
  parser.add_argument("--ordered", action="store_true",
                      help="the input is an lgtrace.ordered_dict export, see to_lean_ordered")
  args = parser.parse_args()
  if args.ordered:
    data = json.loads(args.spec.read_text())
    args.out.write_text(to_lean_ordered(data, args.namespace, args.tactic))
    return
  spec = load(args.spec)
  target = holders(spec, args.holders) if args.holders else spec
  claim = principal_agents(target, args.claim_principal) if args.claim_principal else None
  args.out.write_text(to_lean(target, args.namespace, args.tactic, claim))


if __name__ == "__main__":
  main()
